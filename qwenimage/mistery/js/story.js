async function ask(prompt, answer, line, wrongLines, opt = {}) {
  while (true) {
    if (line) await run(Array.isArray(line) ? line : [line]);
    const pick = await present(prompt);
    if (pick === null) continue;
    const ok = Array.isArray(answer) ? answer.includes(pick) : pick === answer;
    if (ok) {
      $('box').classList.remove('on');
      const o = $('objection'); o.classList.remove('on'); void o.offsetWidth; o.classList.add('on');
      Music.se('reveal'); shake(); await sleep(900);
      return pick;
    }
    Music.se('damage'); shake();
    if (opt.lives) { S.lives--; drawLives(); }
    await run(wrongLines(pick));
    if (opt.lives && S.lives <= 0) return null;
  }
}

